/** 大 GIF 抽帧后的说明（帧数/时长由代码填充） */
export function gifFramesHint(count: number, durationMs: number): string {
  return (
    `这是同一张 GIF 按时间顺序等间隔抽取的 ${count} 帧（总时长约 ${(durationMs / 1000).toFixed(1)} 秒）。` +
    '请综合动作过程与循环感描述，不要逐帧罗列。'
  )
}

